/**
 * Translate Crop Name using cropId or fall back to match by English name
 */
export function translateCrop(cropIdOrName: string, lang: LanguageCode = 'en'): string {
  if (lang === 'en') {
    const entry = CROP_TRANSLATIONS[cropIdOrName];
    if (entry && entry.en) return entry.en;
    return cropIdOrName;
  }

  // 1. Direct match by cropId
  if (CROP_TRANSLATIONS[cropIdOrName]) {
    const translation = CROP_TRANSLATIONS[cropIdOrName][lang];
    if (translation) return translation;
    const fallbackEn = CROP_TRANSLATIONS[cropIdOrName].en;
    if (fallbackEn) return fallbackEn;
  }

  // 2. Search by key name substring
  const clean = cropIdOrName.toLowerCase();
  for (const [id, entry] of Object.entries(CROP_TRANSLATIONS)) {
    const enName = (entry.en || '').toLowerCase();
    if (clean.includes(id.toLowerCase().replace('c_', '')) || enName.includes(clean) || clean.includes(enName.split(' ')[0].toLowerCase())) {
      if (entry[lang]) return entry[lang]!;
      if (entry.en) return entry.en;
    }
  }

  return cropIdOrName;
}


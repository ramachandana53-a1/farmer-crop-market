// Helper to look up recommendations based on selected State & Soil Type
export function getStateAgroRecommendation(stateKey: string, soilTypeFilter?: string): {
  icarZone: IcarZone;
  stateData: IndianState;
  recommendedCrops: Crop[];
  bannerTip: string;
} {
  const normState = stateKey.toUpperCase().replace(/\s+/g, '_');
  const stateData = INDIAN_STATES_DATA[normState] || INDIAN_STATES_DATA['PUNJAB'];
  const icarZone = ICAR_15_ZONES[stateData.primaryIcarZone] || ICAR_15_ZONES['ICAR_ZONE_06'];

  const recommendedCrops = INITIAL_CROPS.filter((c) => 
    stateData.recommendedCropIds.includes(c.cropId) || icarZone.recommendedCropIds.includes(c.cropId)
  );

  let bannerTip = `${stateData.name} (${icarZone.shortName} - ${icarZone.zoneName}): ${icarZone.keyRecommendation}`;
  if (soilTypeFilter) {
    bannerTip += ` Filtered for ${soilTypeFilter} conditions.`;
  }

  return {
    icarZone,
    stateData,
    recommendedCrops,
    bannerTip
  };
}
